# ================= CONFIG =================
FRAC_BITS = 20
SCALE = 1 << FRAC_BITS
OUTPUT_FILE = "features_s7_20_reversed.mem"


# ================= FIXED POINT =================
def float_to_s7_20(val):
    scaled = int(round(val * SCALE))

    if scaled > (2**27 - 1):
        scaled = 2**27 - 1
    elif scaled < -(2**27):
        scaled = -(2**27)

    return scaled & 0x0FFFFFFF


def s7_20_to_float(val):
    if val & (1 << 27):
        val -= (1 << 28)
    return val / SCALE


# ================= WRITE FILE =================
with open(OUTPUT_FILE, "w") as f:

    f.write("// S7.20 (28-bit, 2's complement)\n")
    f.write("// Reversed order per row\n\n")

    for i, row in enumerate(FIXED_SCALED_FEATURES):

        row_rev = row[::-1]   # 🔥 reverse here

        hex_values = []
        debug_info = []

        for val in row_rev:
            fixed = float_to_s7_20(val)
            recon = s7_20_to_float(fixed)

            hex_values.append(f"{fixed:07X}")
            debug_info.append(f"{val:.6f}->{recon:.6f}")

        packed = "_".join(hex_values)

        f.write(f"//mem[{i}] <= 140'h{packed}; "
                f"// {' | '.join(debug_info)}\n")

print(f"✅ File generated: {OUTPUT_FILE}")