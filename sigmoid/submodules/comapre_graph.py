# LUT Parameters
SIGMOID_LUT_SIZE = 1538
SIGMOID_INPUT_MIN = 0.0
SIGMOID_INPUT_MAX = 6.0
SIGMOID_STEP_SIZE = 6.0 / (SIGMOID_LUT_SIZE - 1)  # 0.00390625

# Convert S7.8 to float
def s7_8_to_float(val):
    return val / 256.0

# Original sigmoid function
def sigmoid_original(x):
    return 1 / (1 + np.exp(-x))

# Your S7.8 approximation function
def sigmoid_s7_8_approx(x):
    result = np.zeros_like(x)
    
    for i, xi in enumerate(x):
        if xi < 0:
            # Use symmetry: sigmoid(-x) = 1 - sigmoid(x)
            pos_result = sigmoid_s7_8_approx(np.array([-xi]))[0]
            result[i] = 1.0 - pos_result
        elif xi <= SIGMOID_INPUT_MAX:
            # LUT lookup
            addr = int(xi / SIGMOID_STEP_SIZE)
            if addr >= SIGMOID_LUT_SIZE:
                addr = SIGMOID_LUT_SIZE - 1
            result[i] = s7_8_to_float(sigmoid_lut_s7_8[addr])
        else:
            # Saturate to 1.0
            result[i] = 1.0
            
    return result

